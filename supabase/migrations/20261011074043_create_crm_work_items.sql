-- Công việc & Ghi chú V1: internal operational work, separate from audit_logs.
begin;

insert into public.app_permissions(permission,display_name,sort_order,is_active)
values('work-items','Công việc & Ghi chú',145,true)
on conflict(permission) do update
set display_name=excluded.display_name,sort_order=excluded.sort_order,is_active=true;

create table public.crm_work_items (
  id bigint generated by default as identity primary key,
  title text not null check(length(btrim(title)) between 1 and 200),
  work_type text not null check(work_type in ('pr_post','banner','customer_followup','admin_task','note','other')),
  customer_id bigint references public.customers(id) on delete set null,
  kiosk_id bigint references public.kiosks(id) on delete set null,
  assignee_user_id uuid references public.user_profiles(user_id) on delete set null,
  start_date date,
  due_date date,
  status text not null default 'pending' check(status in ('pending','in_progress','completed','cancelled')),
  note text check(note is null or length(note)<=10000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint crm_work_items_date_order_check check(start_date is null or due_date is null or start_date<=due_date),
  constraint crm_work_items_completed_at_check check(
    (status='completed' and completed_at is not null)
    or (status<>'completed' and completed_at is null)
  ),
  constraint crm_work_items_kiosk_customer_check check(kiosk_id is null or customer_id is not null)
);

comment on table public.crm_work_items is
  'Internal operational work and notes. audit_logs remains the immutable change history.';
comment on column public.crm_work_items.due_date is
  'Business execution/deadline date stored as canonical date without timezone conversion.';

create index crm_work_items_open_due_idx
  on public.crm_work_items(status,due_date,id)
  where status in ('pending','in_progress');
create index crm_work_items_due_date_idx on public.crm_work_items(due_date,id);
create index crm_work_items_customer_id_idx on public.crm_work_items(customer_id) where customer_id is not null;
create index crm_work_items_kiosk_id_idx on public.crm_work_items(kiosk_id) where kiosk_id is not null;
create index crm_work_items_assignee_user_id_idx on public.crm_work_items(assignee_user_id) where assignee_user_id is not null;
create index crm_work_items_created_by_idx on public.crm_work_items(created_by);

create or replace function private.set_crm_work_item_updated_at()
returns trigger language plpgsql set search_path='' as $$
begin
  new.updated_at:=now();
  return new;
end $$;
revoke all on function private.set_crm_work_item_updated_at() from public,anon,authenticated;
create trigger crm_work_items_set_updated_at
before update on public.crm_work_items
for each row execute function private.set_crm_work_item_updated_at();

alter table public.crm_work_items enable row level security;
revoke all on table public.crm_work_items from public,anon,authenticated;
grant select on table public.crm_work_items to authenticated;
grant all on table public.crm_work_items to service_role;
grant usage,select on sequence public.crm_work_items_id_seq to service_role;
create policy crm_work_items_permission_read on public.crm_work_items
for select to authenticated
using((select public.has_user_permission('work-items')));

create or replace function public.get_crm_work_items(
  p_search text default null,
  p_status text default null,
  p_work_type text default null,
  p_assignee_user_id uuid default null,
  p_from_date date default null,
  p_to_date date default null,
  p_include_closed boolean default false
)
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare normalized_search text:=nullif(btrim(coalesce(p_search,'')),'');
begin
  if not public.has_user_permission('work-items') then
    raise exception 'Không có quyền quản lý Công việc & Ghi chú.' using errcode='42501';
  end if;
  if p_status is not null and p_status not in ('pending','in_progress','completed','cancelled') then
    raise exception 'Trạng thái công việc không hợp lệ.';
  end if;
  if p_work_type is not null and p_work_type not in ('pr_post','banner','customer_followup','admin_task','note','other') then
    raise exception 'Loại công việc không hợp lệ.';
  end if;
  if p_from_date is not null and p_to_date is not null and p_from_date>p_to_date then
    raise exception 'Khoảng ngày công việc không hợp lệ.';
  end if;

  return jsonb_build_object(
    'rows',coalesce((
      select jsonb_agg(row_data order by
        case row_data->>'status' when 'in_progress' then 0 when 'pending' then 1 else 2 end,
        nullif(row_data->>'relevant_date','')::date nulls last,
        (row_data->>'updated_at')::timestamptz desc,
        (row_data->>'id')::bigint desc)
      from (
        select to_jsonb(w)||jsonb_build_object(
          'customer_name',c.facebook_name,
          'kiosk_name',k.facebook_name,
          'assignee_name',coalesce(assignee.display_name,assignee.username),
          'assignee_username',assignee.username,
          'creator_name',coalesce(creator.display_name,creator.username,'Tài khoản đã xóa'),
          'relevant_date',coalesce(w.due_date,w.start_date)
        ) row_data
        from public.crm_work_items w
        left join public.customers c on c.id=w.customer_id
        left join public.kiosks k on k.id=w.kiosk_id
        left join public.user_profiles assignee on assignee.user_id=w.assignee_user_id
        left join public.user_profiles creator on creator.user_id=w.created_by
        where (p_status is not null and w.status=p_status or p_status is null and (p_include_closed or w.status in ('pending','in_progress')))
          and (p_work_type is null or w.work_type=p_work_type)
          and (p_assignee_user_id is null or w.assignee_user_id=p_assignee_user_id)
          and (p_from_date is null or coalesce(w.due_date,w.start_date)>=p_from_date)
          and (p_to_date is null or coalesce(w.due_date,w.start_date)<=p_to_date)
          and (normalized_search is null or concat_ws(' ',w.title,w.note,c.facebook_name,k.facebook_name,assignee.display_name,assignee.username) ilike '%'||normalized_search||'%')
      ) rows_source
    ),'[]'::jsonb),
    'customers',coalesce((
      select jsonb_agg(jsonb_build_object('id',c.id,'name',c.facebook_name) order by c.facebook_name,c.id)
      from public.customers c
    ),'[]'::jsonb),
    'kiosks',coalesce((
      select jsonb_agg(jsonb_build_object('id',k.id,'customer_id',k.customer_id,'name',k.facebook_name) order by k.facebook_name,k.id)
      from public.kiosks k
    ),'[]'::jsonb),
    'assignees',coalesce((
      select jsonb_agg(jsonb_build_object('user_id',up.user_id,'name',coalesce(up.display_name,up.username),'username',up.username) order by coalesce(up.display_name,up.username),up.user_id)
      from public.user_profiles up where up.status='active' and up.web_access_enabled
    ),'[]'::jsonb)
  );
end $$;

create or replace function public.save_crm_work_item(
  p_id bigint,
  p_title text,
  p_work_type text,
  p_customer_id bigint,
  p_kiosk_id bigint,
  p_assignee_user_id uuid,
  p_start_date date,
  p_due_date date,
  p_status text,
  p_note text default null
)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  actor public.user_profiles%rowtype;
  previous public.crm_work_items%rowtype;
  saved public.crm_work_items%rowtype;
  normalized_title text:=btrim(coalesce(p_title,''));
  normalized_type text:=lower(btrim(coalesce(p_work_type,'')));
  normalized_status text:=lower(btrim(coalesce(p_status,'')));
  normalized_note text:=nullif(btrim(coalesce(p_note,'')),'');
begin
  if not public.has_user_permission('work-items') then
    raise exception 'Không có quyền quản lý Công việc & Ghi chú.' using errcode='42501';
  end if;
  select * into actor from public.user_profiles where user_id=auth.uid();
  if actor.user_id is null then raise exception 'Không tìm thấy tài khoản thực hiện.' using errcode='42501'; end if;
  if length(normalized_title) not between 1 and 200 then raise exception 'Tiêu đề phải có từ 1 đến 200 ký tự.'; end if;
  if normalized_type not in ('pr_post','banner','customer_followup','admin_task','note','other') then raise exception 'Loại công việc không hợp lệ.'; end if;
  if normalized_status not in ('pending','in_progress','completed','cancelled') then raise exception 'Trạng thái công việc không hợp lệ.'; end if;
  if normalized_note is not null and length(normalized_note)>10000 then raise exception 'Nội dung tối đa 10.000 ký tự.'; end if;
  if p_start_date is not null and p_due_date is not null and p_start_date>p_due_date then raise exception 'Ngày bắt đầu không được sau ngày thực hiện/hạn.'; end if;
  if p_customer_id is not null and not exists(select 1 from public.customers where id=p_customer_id) then raise exception 'Khách hàng không tồn tại.'; end if;
  if p_kiosk_id is not null and p_customer_id is null then raise exception 'Cần chọn Khách hàng trước khi chọn Kiosk.'; end if;
  if p_kiosk_id is not null and not exists(select 1 from public.kiosks where id=p_kiosk_id and customer_id=p_customer_id) then raise exception 'Kiosk không thuộc Khách hàng đã chọn.'; end if;
  if p_assignee_user_id is not null and not exists(
    select 1 from public.user_profiles where user_id=p_assignee_user_id and status='active' and web_access_enabled
  ) then raise exception 'Người phụ trách không phải tài khoản CRM đang hoạt động.'; end if;

  if p_id is null then
    insert into public.crm_work_items(title,work_type,customer_id,kiosk_id,assignee_user_id,start_date,due_date,status,note,created_by,completed_at)
    values(normalized_title,normalized_type,p_customer_id,p_kiosk_id,p_assignee_user_id,p_start_date,p_due_date,normalized_status,normalized_note,auth.uid(),case when normalized_status='completed' then now() else null end)
    returning * into saved;
  else
    select * into previous from public.crm_work_items where id=p_id for update;
    if previous.id is null then raise exception 'Công việc không tồn tại.'; end if;
    if previous.status in ('completed','cancelled') and normalized_status<>previous.status then
      raise exception 'Công việc đã kết thúc không thể mở lại trong phiên bản này.';
    end if;
    update public.crm_work_items set
      title=normalized_title,work_type=normalized_type,customer_id=p_customer_id,kiosk_id=p_kiosk_id,
      assignee_user_id=p_assignee_user_id,start_date=p_start_date,due_date=p_due_date,status=normalized_status,note=normalized_note,
      completed_at=case when normalized_status='completed' then coalesce(previous.completed_at,now()) else null end
    where id=p_id returning * into saved;
  end if;

  insert into public.audit_logs(actor_id,actor_name,actor_role,actor_type,module,entity,record_id,action,before,after,reason)
  values(auth.uid(),coalesce(actor.display_name,actor.username,'Quản trị viên'),case when actor.is_system_admin then 'system_admin' else 'staff' end,'staff',
    'WorkItems','crm_work_items',saved.id::text,case when previous.id is null then 'create_work_item' else 'update_work_item' end,
    case when previous.id is null then null else to_jsonb(previous) end,to_jsonb(saved),coalesce(normalized_note,normalized_title));
  return to_jsonb(saved);
end $$;

create or replace function public.set_crm_work_item_status(p_id bigint,p_status text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  actor public.user_profiles%rowtype;
  previous public.crm_work_items%rowtype;
  saved public.crm_work_items%rowtype;
  normalized_status text:=lower(btrim(coalesce(p_status,'')));
begin
  if not public.has_user_permission('work-items') then
    raise exception 'Không có quyền quản lý Công việc & Ghi chú.' using errcode='42501';
  end if;
  if normalized_status not in ('completed','cancelled') then raise exception 'Chỉ hỗ trợ hoàn thành hoặc hủy công việc.'; end if;
  select * into actor from public.user_profiles where user_id=auth.uid();
  select * into previous from public.crm_work_items where id=p_id for update;
  if previous.id is null then raise exception 'Công việc không tồn tại.'; end if;
  if previous.status in ('completed','cancelled') then
    if previous.status=normalized_status then return to_jsonb(previous); end if;
    raise exception 'Công việc đã kết thúc không thể đổi trạng thái.';
  end if;
  update public.crm_work_items set status=normalized_status,completed_at=case when normalized_status='completed' then now() else null end
  where id=p_id returning * into saved;
  insert into public.audit_logs(actor_id,actor_name,actor_role,actor_type,module,entity,record_id,action,before,after,reason)
  values(auth.uid(),coalesce(actor.display_name,actor.username,'Quản trị viên'),case when actor.is_system_admin then 'system_admin' else 'staff' end,'staff',
    'WorkItems','crm_work_items',saved.id::text,case when normalized_status='completed' then 'complete_work_item' else 'cancel_work_item' end,
    to_jsonb(previous),to_jsonb(saved),case when normalized_status='completed' then 'Hoàn thành công việc' else 'Hủy công việc' end);
  return to_jsonb(saved);
end $$;

revoke all on function public.get_crm_work_items(text,text,text,uuid,date,date,boolean) from public,anon;
revoke all on function public.save_crm_work_item(bigint,text,text,bigint,bigint,uuid,date,date,text,text) from public,anon;
revoke all on function public.set_crm_work_item_status(bigint,text) from public,anon;
grant execute on function public.get_crm_work_items(text,text,text,uuid,date,date,boolean) to authenticated;
grant execute on function public.save_crm_work_item(bigint,text,text,bigint,bigint,uuid,date,date,text,text) to authenticated;
grant execute on function public.set_crm_work_item_status(bigint,text) to authenticated;

commit;
