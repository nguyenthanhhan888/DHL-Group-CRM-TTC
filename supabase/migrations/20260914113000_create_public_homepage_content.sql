create or replace function public.get_public_homepage_content()
returns jsonb language sql stable security definer set search_path = pg_catalog, public as $$
  select jsonb_build_object(
    'content', jsonb_build_object(
      'heroTitle', h.hero_title,
      'heroSubtitle', h.hero_subtitle,
      'heroImageUrl', h.hero_image_url,
      'heroGroupCtaLabel', h.hero_group_cta_label,
      'heroGroupCtaUrl', h.hero_group_cta_url,
      'heroKioskCtaLabel', h.hero_kiosk_cta_label,
      'heroKioskCtaRoute', h.hero_kiosk_cta_route,
      'postingRules', h.posting_rules,
      'zaloContacts', coalesce((select jsonb_agg(jsonb_build_object(
        'label', item->>'label', 'url', item->>'url'
      )) from jsonb_array_elements(h.zalo_contacts) item), '[]'::jsonb),
      'hotlineLabel', h.hotline_label,
      'hotlineNumber', h.hotline_number,
      'fanpageLabel', h.fanpage_label,
      'fanpageUrl', h.fanpage_url,
      'communityLinks', coalesce((select jsonb_agg(jsonb_build_object(
        'key', item->>'key', 'name', item->>'name', 'url', item->>'url',
        'enabled', case lower(coalesce(item->>'enabled', 'true')) when 'false' then false else true end,
        'display_order', case when coalesce(item->>'display_order', '') ~ '^[0-9]+$' then (item->>'display_order')::integer else 0 end
      ) order by case when coalesce(item->>'display_order', '') ~ '^[0-9]+$' then (item->>'display_order')::integer else 0 end)
      from jsonb_array_elements(h.community_links) item), '[]'::jsonb),
      'sectionVisibility', h.section_visibility,
      'sectionOrder', to_jsonb(h.section_order)
    ),
    'featuredBusinesses', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', b.id, 'name', b.name, 'imageUrl', b.image_url, 'category', b.category,
        'shortDescription', b.short_description, 'address', b.address,
        'facebookUrl', b.facebook_url, 'zaloContact', b.zalo_contact, 'phone', b.phone,
        'badge', b.badge, 'displayOrder', b.display_order
      ) order by b.display_order, b.id)
      from public.featured_businesses b
      where b.archived_at is null and b.enabled
        and (b.visibility_start is null or b.visibility_start <= now())
        and (b.visibility_end is null or b.visibility_end >= now())
    ), '[]'::jsonb)
  )
  from public.homepage_content h where h.id = 1;
$$;
create or replace function public.get_homepage_admin_data()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
begin
  if not public.has_user_permission('homepage-content') then
    raise exception 'Không có quyền quản lý nội dung trang chủ.' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'content', (select to_jsonb(h) from public.homepage_content h where h.id = 1),
    'featuredBusinesses', coalesce((select jsonb_agg(to_jsonb(b) order by b.display_order, b.id)
      from public.featured_businesses b where b.archived_at is null), '[]'::jsonb)
  );
end;
$$;
create or replace function public.save_homepage_content(p_content jsonb)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  actor public.user_profiles%rowtype;
  before_content public.homepage_content%rowtype;
  saved_content public.homepage_content%rowtype;
  links jsonb := coalesce(p_content->'communityLinks', '[]'::jsonb);
  zalo jsonb := coalesce(p_content->'zaloContacts', '[]'::jsonb);
  visibility jsonb := coalesce(p_content->'sectionVisibility', '{}'::jsonb);
  normalized_section_order text[];
begin
  if not public.has_user_permission('homepage-content') then
    raise exception 'Không có quyền quản lý nội dung trang chủ.' using errcode = '42501';
  end if;
  if jsonb_typeof(links) <> 'array' or jsonb_array_length(links) > 12 then raise exception 'Danh sách liên kết không hợp lệ.'; end if;
  if jsonb_typeof(zalo) <> 'array' or jsonb_array_length(zalo) > 5 then raise exception 'Danh sách Zalo không hợp lệ.'; end if;
  if jsonb_typeof(visibility) <> 'object' then raise exception 'Cấu hình hiển thị không hợp lệ.'; end if;
  select coalesce(array_agg(value), array[]::text[]) into normalized_section_order
  from jsonb_array_elements_text(coalesce(p_content->'sectionOrder', '[]'::jsonb));
  if cardinality(normalized_section_order) <> 5 or normalized_section_order @> array['featured_businesses','kiosk_services','posting_rules','community_links','contact']::text[] is false then
    raise exception 'Thứ tự section không hợp lệ.';
  end if;
  if nullif(btrim(p_content->>'heroTitle'), '') is null or nullif(btrim(p_content->>'heroSubtitle'), '') is null then
    raise exception 'Tiêu đề và mô tả Hero là bắt buộc.';
  end if;
  if coalesce(p_content->>'heroKioskCtaRoute', '') !~ '^#/[a-z0-9-]+$' then raise exception 'Route CTA Kiosk không hợp lệ.'; end if;

  select * into actor from public.user_profiles where user_id = auth.uid();
  select * into before_content from public.homepage_content where id = 1 for update;
  update public.homepage_content set
    hero_title = left(btrim(p_content->>'heroTitle'), 180),
    hero_subtitle = left(btrim(p_content->>'heroSubtitle'), 600),
    hero_image_url = nullif(btrim(p_content->>'heroImageUrl'), ''),
    hero_group_cta_label = left(btrim(p_content->>'heroGroupCtaLabel'), 80),
    hero_group_cta_url = btrim(p_content->>'heroGroupCtaUrl'),
    hero_kiosk_cta_label = left(btrim(p_content->>'heroKioskCtaLabel'), 80),
    hero_kiosk_cta_route = btrim(p_content->>'heroKioskCtaRoute'),
    posting_rules = left(coalesce(p_content->>'postingRules', ''), 5000),
    zalo_contacts = zalo,
    hotline_label = left(btrim(p_content->>'hotlineLabel'), 60),
    hotline_number = left(regexp_replace(coalesce(p_content->>'hotlineNumber',''), '[^0-9+]', '', 'g'), 20),
    fanpage_label = left(btrim(p_content->>'fanpageLabel'), 80),
    fanpage_url = btrim(p_content->>'fanpageUrl'),
    community_links = links,
    section_visibility = visibility,
    section_order = normalized_section_order,
    updated_by = auth.uid()
  where id = 1 returning * into saved_content;
  insert into public.audit_logs(actor_id, actor_name, actor_role, actor_type, module, entity, record_id, action, before, after, reason)
  values (auth.uid(), coalesce(actor.display_name, actor.username, 'Quản trị viên'),
    case when actor.is_system_admin then 'system_admin' else 'staff' end, 'staff',
    'Homepage', 'homepage_content', '1', 'update_homepage_content',
    to_jsonb(before_content), to_jsonb(saved_content), 'Cập nhật nội dung trang chủ');
  return to_jsonb(saved_content);
end;
$$;
create or replace function public.save_featured_business(p_business jsonb)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  actor public.user_profiles%rowtype;
  before_business public.featured_businesses%rowtype;
  saved_business public.featured_businesses%rowtype;
  business_id bigint := nullif(p_business->>'id', '')::bigint;
  start_at timestamptz := nullif(p_business->>'visibilityStart', '')::timestamptz;
  end_at timestamptz := nullif(p_business->>'visibilityEnd', '')::timestamptz;
  action_name text;
begin
  if not public.has_user_permission('homepage-content') then
    raise exception 'Không có quyền quản lý nội dung trang chủ.' using errcode = '42501';
  end if;
  if nullif(btrim(p_business->>'name'), '') is null or nullif(btrim(p_business->>'category'), '') is null then
    raise exception 'Tên và danh mục doanh nghiệp là bắt buộc.';
  end if;
  if start_at is not null and end_at is not null and start_at > end_at then raise exception 'Khoảng hiển thị không hợp lệ.'; end if;
  select * into actor from public.user_profiles where user_id = auth.uid();
  if business_id is null then
    insert into public.featured_businesses(name,image_url,category,short_description,address,facebook_url,zalo_contact,phone,badge,enabled,display_order,visibility_start,visibility_end,created_by)
    values (left(btrim(p_business->>'name'),160),nullif(btrim(p_business->>'imageUrl'),''),left(btrim(p_business->>'category'),100),
      nullif(left(btrim(p_business->>'shortDescription'),500),''),nullif(btrim(p_business->>'address'),''),nullif(btrim(p_business->>'facebookUrl'),''),
      nullif(btrim(p_business->>'zaloContact'),''),nullif(btrim(p_business->>'phone'),''),nullif(left(btrim(p_business->>'badge'),50),''),
      coalesce((p_business->>'enabled')::boolean,true),greatest(coalesce((p_business->>'displayOrder')::integer,0),0),start_at,end_at,auth.uid())
    returning * into saved_business;
    action_name := 'create_featured_business';
  else
    select * into before_business from public.featured_businesses where id = business_id and archived_at is null for update;
    if before_business.id is null then raise exception 'Doanh nghiệp không tồn tại hoặc đã lưu trữ.'; end if;
    update public.featured_businesses set
      name=left(btrim(p_business->>'name'),160), image_url=nullif(btrim(p_business->>'imageUrl'),''), category=left(btrim(p_business->>'category'),100),
      short_description=nullif(left(btrim(p_business->>'shortDescription'),500),''), address=nullif(btrim(p_business->>'address'),''),
      facebook_url=nullif(btrim(p_business->>'facebookUrl'),''), zalo_contact=nullif(btrim(p_business->>'zaloContact'),''), phone=nullif(btrim(p_business->>'phone'),''),
      badge=nullif(left(btrim(p_business->>'badge'),50),''), enabled=coalesce((p_business->>'enabled')::boolean,true),
      display_order=greatest(coalesce((p_business->>'displayOrder')::integer,0),0), visibility_start=start_at, visibility_end=end_at
    where id=business_id returning * into saved_business;
    action_name := 'update_featured_business';
  end if;
  insert into public.audit_logs(actor_id,actor_name,actor_role,actor_type,module,entity,record_id,action,before,after,reason)
  values (auth.uid(),coalesce(actor.display_name,actor.username,'Quản trị viên'),case when actor.is_system_admin then 'system_admin' else 'staff' end,'staff',
    'Homepage','featured_businesses',saved_business.id::text,action_name,case when before_business.id is null then null else to_jsonb(before_business) end,to_jsonb(saved_business),saved_business.name);
  return to_jsonb(saved_business);
end;
$$;
create or replace function public.archive_featured_business(p_id bigint)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  actor public.user_profiles%rowtype;
  before_business public.featured_businesses%rowtype;
  saved_business public.featured_businesses%rowtype;
begin
  if not public.has_user_permission('homepage-content') then raise exception 'Không có quyền quản lý nội dung trang chủ.' using errcode='42501'; end if;
  select * into actor from public.user_profiles where user_id=auth.uid();
  select * into before_business from public.featured_businesses where id=p_id and archived_at is null for update;
  if before_business.id is null then raise exception 'Doanh nghiệp không tồn tại hoặc đã lưu trữ.'; end if;
  update public.featured_businesses set archived_at=now(), archived_by=auth.uid() where id=p_id returning * into saved_business;
  insert into public.audit_logs(actor_id,actor_name,actor_role,actor_type,module,entity,record_id,action,before,after,reason)
  values (auth.uid(),coalesce(actor.display_name,actor.username,'Quản trị viên'),case when actor.is_system_admin then 'system_admin' else 'staff' end,'staff',
    'Homepage','featured_businesses',saved_business.id::text,'archive_featured_business',to_jsonb(before_business),to_jsonb(saved_business),saved_business.name);
  return to_jsonb(saved_business);
end;
$$;
