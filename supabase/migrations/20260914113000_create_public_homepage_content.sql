insert into public.app_permissions(permission, display_name, sort_order, is_active)
values ('homepage-content', 'Nội dung trang chủ', 205, true)
on conflict (permission) do update
set display_name = excluded.display_name,
    sort_order = excluded.sort_order,
    is_active = true;
create table if not exists public.homepage_content (
  id smallint primary key default 1,
  hero_title text not null,
  hero_subtitle text not null,
  hero_image_url text,
  hero_group_cta_label text not null,
  hero_group_cta_url text not null,
  hero_kiosk_cta_label text not null,
  hero_kiosk_cta_route text not null default '#/register',
  posting_rules text not null,
  zalo_contacts jsonb not null default '[]'::jsonb,
  hotline_label text not null,
  hotline_number text not null,
  fanpage_label text not null default 'Fanpage Admin',
  fanpage_url text not null,
  community_links jsonb not null default '[]'::jsonb,
  section_visibility jsonb not null default '{}'::jsonb,
  section_order text[] not null default array['featured_businesses','kiosk_services','posting_rules','community_links','contact']::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  constraint homepage_content_singleton_check check (id = 1),
  constraint homepage_content_zalo_array_check check (jsonb_typeof(zalo_contacts) = 'array'),
  constraint homepage_content_links_array_check check (jsonb_typeof(community_links) = 'array'),
  constraint homepage_content_visibility_object_check check (jsonb_typeof(section_visibility) = 'object'),
  constraint homepage_content_kiosk_route_check check (hero_kiosk_cta_route ~ '^#/[a-z0-9-]+$')
);
create table if not exists public.featured_businesses (
  id bigint generated by default as identity primary key,
  name text not null,
  image_url text,
  category text not null,
  short_description text,
  address text,
  facebook_url text,
  zalo_contact text,
  phone text,
  badge text,
  enabled boolean not null default true,
  display_order integer not null default 0,
  visibility_start timestamptz,
  visibility_end timestamptz,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete set null,
  constraint featured_business_name_check check (length(btrim(name)) between 1 and 160),
  constraint featured_business_category_check check (length(btrim(category)) between 1 and 100),
  constraint featured_business_description_check check (short_description is null or length(short_description) <= 500),
  constraint featured_business_badge_check check (badge is null or length(badge) <= 50),
  constraint featured_business_display_order_check check (display_order between 0 and 100000),
  constraint featured_business_visibility_check check (visibility_start is null or visibility_end is null or visibility_start <= visibility_end)
);
create index if not exists featured_business_public_order_idx
  on public.featured_businesses(display_order, id) where archived_at is null and enabled;
