create or replace function public.admin_save_promotion(promotion_id_input bigint,promotion_input jsonb,category_ids_input bigint[] default '{}'::bigint[],business_type_ids_input bigint[] default '{}'::bigint[])
returns jsonb language plpgsql security definer set search_path='' as $function$
declare saved public.promotions%rowtype; scope_value text:=coalesce(promotion_input->>'scope_type','all');
begin
  if not exists(select 1 from public.user_roles r where r.user_id=(select auth.uid()) and pg_catalog.lower(r.role)='admin' and r.is_active) then raise exception 'Bạn không có quyền quản lý mã giảm giá.' using errcode='42501'; end if;
  if scope_value='category' and coalesce(pg_catalog.array_length(category_ids_input,1),0)=0 then raise exception 'Vui lòng chọn ít nhất một danh mục.' using errcode='22023'; end if;
  if scope_value='business_type' and coalesce(pg_catalog.array_length(business_type_ids_input,1),0)=0 then raise exception 'Vui lòng chọn ít nhất một loại hình kinh doanh.' using errcode='22023'; end if;
  if scope_value='category' and exists(select 1 from pg_catalog.unnest(category_ids_input) id left join public.categories c on c.id=id where c.id is null) then raise exception 'Danh mục áp dụng không hợp lệ.' using errcode='22023'; end if;
