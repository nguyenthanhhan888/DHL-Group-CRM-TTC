-- Discount / Promotion Engine V1. Forward-only; no historical migration is changed.
-- VND rounding rule: percentage discounts are rounded down to the nearest integer.

create table public.promotions (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  description text,
  discount_type text not null check (discount_type in ('percentage','fixed_amount','bonus_months')),
  discount_value bigint not null check (discount_value > 0),
  max_discount_amount bigint check (max_discount_amount is null or max_discount_amount > 0),
  minimum_order_amount bigint check (minimum_order_amount is null or minimum_order_amount >= 0),
  minimum_kiosk_count integer check (minimum_kiosk_count is null or minimum_kiosk_count > 0),
  minimum_months integer check (minimum_months is null or minimum_months > 0),
  starts_at timestamptz,
  ends_at timestamptz,
  usage_limit_total integer check (usage_limit_total is null or usage_limit_total > 0),
  usage_limit_per_customer integer check (usage_limit_per_customer is null or usage_limit_per_customer > 0),
  scope_type text not null default 'all' check (scope_type in ('all','category','business_type')),
  is_active boolean not null default true,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint promotions_percentage_value check (discount_type <> 'percentage' or discount_value <= 100),
  constraint promotions_max_only_percentage check (max_discount_amount is null or discount_type = 'percentage'),
  constraint promotions_valid_period check (ends_at is null or starts_at is null or ends_at >= starts_at),
  constraint promotions_code_normalized check (code = pg_catalog.upper(pg_catalog.btrim(code)) and code <> '')
);

create unique index promotions_code_ci_uidx on public.promotions (pg_catalog.upper(pg_catalog.btrim(code)));

create table public.promotion_categories (
  promotion_id bigint not null references public.promotions(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  primary key (promotion_id, category_id)
);

create table public.promotion_business_types (
  promotion_id bigint not null references public.promotions(id) on delete cascade,
  business_type_id bigint not null references public.business_types(id) on delete restrict,
  primary key (promotion_id, business_type_id)
);

