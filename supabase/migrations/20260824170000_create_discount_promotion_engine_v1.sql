create table public.promotion_usages (
  id bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete restrict,
  registration_batch_id bigint not null references public.registration_batches(id) on delete restrict,
  payment_id bigint not null references public.payments(id) on delete restrict,
  code_snapshot text not null,
  discount_type_snapshot text not null check (discount_type_snapshot in ('percentage','fixed_amount','bonus_months')),
  discount_value_snapshot bigint not null,
  subtotal_before_discount bigint not null check (subtotal_before_discount > 0),
  eligible_subtotal bigint not null check (eligible_subtotal >= 0 and eligible_subtotal <= subtotal_before_discount),
  discount_amount bigint not null check (discount_amount >= 0 and discount_amount <= eligible_subtotal),
  final_amount bigint not null check (final_amount > 0),
  total_bonus_months integer not null default 0 check (total_bonus_months >= 0),
  created_at timestamptz not null default pg_catalog.now(),
  unique (registration_batch_id),
  unique (payment_id),
  check (discount_value_snapshot > 0),
  check (final_amount = subtotal_before_discount - discount_amount)
);

