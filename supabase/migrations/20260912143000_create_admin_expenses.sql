-- Minimal Admin expense ledger. Apply manually after QA; this migration does not
-- modify payments or the revenue source of truth.
begin;
insert into public.app_permissions(permission, display_name, sort_order, is_active)
values ('expenses', 'Quản lý chi phí', 65, true)
on conflict (permission) do update
set display_name = excluded.display_name,
    sort_order = excluded.sort_order,
    is_active = true;
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  category text not null,
  amount numeric(14,2) not null,
  expense_date date not null,
  employee_user_id uuid references public.user_profiles(user_id) on delete set null,
  salary_period date,
  payment_method text not null,
  note text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete set null,
  constraint expenses_category_check check (category = any (array[
    'salary', 'bonus', 'advertising', 'infrastructure', 'refund', 'other'
  ]::text[])),
  constraint expenses_amount_positive_check check (amount > 0),
  constraint expenses_payment_method_check check (length(btrim(payment_method)) between 1 and 50),
  constraint expenses_salary_fields_check check (
    (category = 'salary' and employee_user_id is not null and salary_period is not null and extract(day from salary_period) = 1)
    or (category <> 'salary' and salary_period is null)
  )
);
create index if not exists expenses_active_date_idx
  on public.expenses(expense_date desc, id desc) where archived_at is null;
create index if not exists expenses_category_date_idx
  on public.expenses(category, expense_date desc) where archived_at is null;
create index if not exists expenses_salary_lookup_idx
  on public.expenses(employee_user_id, salary_period) where category = 'salary' and archived_at is null;
comment on table public.expenses is
  'Administrative expense source of truth, separate from Kiosk revenue payments.';
comment on column public.expenses.salary_period is
  'First day of the represented salary month; required only for salary expenses.';
