create or replace function public.get_expenses_data(
  p_start_date date default null,
  p_end_date date default null,
  p_category text default null,
  p_employee_user_id uuid default null,
  p_include_archived boolean default false
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  result jsonb;
begin
  if not public.has_user_permission('expenses') then
    raise exception 'Không có quyền quản lý chi phí.' using errcode = '42501';
  end if;
  if p_start_date is not null and p_end_date is not null and p_start_date > p_end_date then
    raise exception 'Khoảng ngày chi phí không hợp lệ.';
  end if;
  if p_category is not null and p_category <> all (array['salary','bonus','advertising','infrastructure','refund','other']::text[]) then
    raise exception 'Danh mục chi phí không hợp lệ.';
  end if;

  with filtered as materialized (
    select e.*, coalesce(up.display_name, up.username, 'Người dùng đã xóa') as employee_name,
      coalesce(creator.display_name, creator.username, 'Quản trị viên') as creator_name
    from public.expenses e
    left join public.user_profiles up on up.user_id = e.employee_user_id
    left join public.user_profiles creator on creator.user_id = e.created_by
    where (p_include_archived or e.archived_at is null)
      and (p_start_date is null or e.expense_date >= p_start_date)
      and (p_end_date is null or e.expense_date <= p_end_date)
      and (p_category is null or e.category = p_category)
      and (p_employee_user_id is null or e.employee_user_id = p_employee_user_id)
  )
  select jsonb_build_object(
    'rows', coalesce((select jsonb_agg(to_jsonb(f) order by f.expense_date desc, f.id desc) from filtered f), '[]'::jsonb),
    'totalAmount', coalesce((select sum(f.amount) from filtered f), 0),
    'totalRows', (select count(*) from filtered),
    'employees', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', up.user_id,
        'display_name', coalesce(up.display_name, up.username, 'Chưa có tên'),
        'username', up.username
      ) order by coalesce(up.display_name, up.username, ''))
      from public.user_profiles up
      where up.status = 'active'
    ), '[]'::jsonb)
  ) into result;
  return result;
end;
$$;
create or replace function public.check_duplicate_salary_expense(
  p_employee_user_id uuid,
  p_salary_period date,
  p_exclude_id bigint default null
)
returns boolean
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
begin
  if not public.has_user_permission('expenses') then
    raise exception 'Không có quyền quản lý chi phí.' using errcode = '42501';
  end if;
  if p_employee_user_id is null or p_salary_period is null then return false; end if;
  return exists (
    select 1 from public.expenses e
    where e.category = 'salary'
      and e.employee_user_id = p_employee_user_id
      and e.salary_period = date_trunc('month', p_salary_period)::date
      and e.archived_at is null
      and (p_exclude_id is null or e.id <> p_exclude_id)
  );
end;
$$;
create or replace function public.save_expense(
  p_id bigint,
  p_category text,
  p_amount numeric,
  p_expense_date date,
  p_employee_user_id uuid,
  p_salary_period date,
  p_payment_method text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  actor public.user_profiles%rowtype;
  before_expense public.expenses%rowtype;
  saved_expense public.expenses%rowtype;
  normalized_category text := lower(btrim(coalesce(p_category, '')));
  normalized_method text := lower(btrim(coalesce(p_payment_method, '')));
  normalized_note text := nullif(btrim(coalesce(p_note, '')), '');
  normalized_period date := case when p_salary_period is null then null else date_trunc('month', p_salary_period)::date end;
  duplicate_salary boolean := false;
  employee_name text;
  log_action text;
begin
  if not public.has_user_permission('expenses') then
    raise exception 'Không có quyền quản lý chi phí.' using errcode = '42501';
  end if;
  if normalized_category <> all (array['salary','bonus','advertising','infrastructure','refund','other']::text[]) then
    raise exception 'Danh mục chi phí không hợp lệ.';
  end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Số tiền phải lớn hơn 0.'; end if;
  if p_expense_date is null then raise exception 'Ngày chi là bắt buộc.'; end if;
  if normalized_method = '' or length(normalized_method) > 50 then raise exception 'Phương thức chi không hợp lệ.'; end if;
  if normalized_category = 'salary' and (p_employee_user_id is null or normalized_period is null) then
    raise exception 'Lương cần có nhân viên và kỳ lương.';
  end if;
  if normalized_category <> 'salary' then normalized_period := null; end if;
  if p_employee_user_id is not null and not exists (select 1 from public.user_profiles where user_id = p_employee_user_id) then
    raise exception 'Nhân viên không tồn tại.';
  end if;

  select * into actor from public.user_profiles where user_id = auth.uid();
  if actor.user_id is null then raise exception 'Không tìm thấy tài khoản thực hiện.' using errcode = '42501'; end if;
  duplicate_salary := normalized_category = 'salary' and exists (
    select 1 from public.expenses e
    where e.category = 'salary' and e.employee_user_id = p_employee_user_id
      and e.salary_period = normalized_period and e.archived_at is null
      and (p_id is null or e.id <> p_id)
  );

  if p_id is null then
    insert into public.expenses(category, amount, expense_date, employee_user_id, salary_period, payment_method, note, created_by)
    values (normalized_category, p_amount, p_expense_date, p_employee_user_id, normalized_period, normalized_method, normalized_note, auth.uid())
    returning * into saved_expense;
    log_action := case when normalized_category = 'salary' then 'create_salary_expense' else 'create_expense' end;
  else
    select * into before_expense from public.expenses where id = p_id and archived_at is null for update;
    if before_expense.id is null then raise exception 'Khoản chi không tồn tại hoặc đã hủy.'; end if;
    update public.expenses set
      category = normalized_category,
      amount = p_amount,
      expense_date = p_expense_date,
      employee_user_id = p_employee_user_id,
      salary_period = normalized_period,
      payment_method = normalized_method,
      note = normalized_note
    where id = p_id returning * into saved_expense;
    log_action := 'update_expense';
  end if;

  select coalesce(up.display_name, up.username, 'Nhân viên') into employee_name
  from public.user_profiles up where up.user_id = saved_expense.employee_user_id;
  insert into public.audit_logs(actor_id, actor_name, actor_role, actor_type, module, entity, record_id, action, before, after, reason)
  values (
    auth.uid(), coalesce(actor.display_name, actor.username, 'Quản trị viên'),
    case when actor.is_system_admin then 'system_admin' else 'staff' end, 'staff',
    'Expense', 'expenses', saved_expense.id::text, log_action,
    case when before_expense.id is null then null else to_jsonb(before_expense) end,
    to_jsonb(saved_expense) || jsonb_build_object('employee_name', employee_name),
    normalized_note
  );
  return jsonb_build_object('expense', to_jsonb(saved_expense), 'duplicateSalary', duplicate_salary);
end;
$$;
create or replace function public.archive_expense(p_id bigint, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  actor public.user_profiles%rowtype;
  before_expense public.expenses%rowtype;
  saved_expense public.expenses%rowtype;
  normalized_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if not public.has_user_permission('expenses') then
    raise exception 'Không có quyền quản lý chi phí.' using errcode = '42501';
  end if;
  select * into actor from public.user_profiles where user_id = auth.uid();
  select * into before_expense from public.expenses where id = p_id and archived_at is null for update;
  if before_expense.id is null then raise exception 'Khoản chi không tồn tại hoặc đã hủy.'; end if;
  update public.expenses set archived_at = now(), archived_by = auth.uid()
  where id = p_id returning * into saved_expense;
  insert into public.audit_logs(actor_id, actor_name, actor_role, actor_type, module, entity, record_id, action, before, after, reason)
  values (
    auth.uid(), coalesce(actor.display_name, actor.username, 'Quản trị viên'),
    case when actor.is_system_admin then 'system_admin' else 'staff' end, 'staff',
    'Expense', 'expenses', saved_expense.id::text, 'archive_expense',
    to_jsonb(before_expense), to_jsonb(saved_expense), coalesce(normalized_reason, 'Hủy khoản chi')
  );
  return to_jsonb(saved_expense);
end;
$$;
create or replace function public.get_expense_report_summary(p_start_date date default null, p_end_date date default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
begin
  if not public.has_user_permission('reports') then
    raise exception 'Không có quyền xem báo cáo.' using errcode = '42501';
  end if;
  if p_start_date is not null and p_end_date is not null and p_start_date > p_end_date then
    raise exception 'Khoảng ngày báo cáo không hợp lệ.';
  end if;
  return jsonb_build_object(
    'totalExpense', coalesce((select sum(e.amount) from public.expenses e
      where e.archived_at is null
        and (p_start_date is null or e.expense_date >= p_start_date)
        and (p_end_date is null or e.expense_date <= p_end_date)), 0)
  );
end;
$$;
