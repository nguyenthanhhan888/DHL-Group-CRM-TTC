test('normal creation records auth.uid and deleting the creator preserves the Work Item',async()=>{
  const saved=await save({title:'Giữ lịch sử người tạo'});
  assert.equal(saved.created_by,staff);
  await db.exec('reset role');
  const column=(await db.query("select is_nullable from information_schema.columns where table_schema='public' and table_name='crm_work_items' and column_name='created_by'")).rows[0];
  assert.equal(column.is_nullable,'YES');
  await db.query('delete from public.user_permissions where user_id=$1',[staff]);
  await db.query('delete from public.user_profiles where user_id=$1',[staff]);
  await db.query('delete from auth.users where id=$1',[staff]);
  const retained=(await db.query('select title,created_by from public.crm_work_items where id=$1',[saved.id])).rows[0];
  assert.equal(retained.title,'Giữ lịch sử người tạo');assert.equal(retained.created_by,null);
  await asUser(admin);
  const rendered=(await list()).rows.find(item=>item.id===saved.id);
  assert.equal(rendered.creator_name,'Tài khoản đã xóa');
});

test('editing preserves stored dates and closed work cannot be reopened',async()=>{
  const original=await save({startDate:'2026-10-10',dueDate:'2026-10-20'});
  const edited=await save({id:original.id,title:'Đã sửa',startDate:original.start_date,dueDate:original.due_date});
  assert.equal(edited.start_date,'2026-10-10');assert.equal(edited.due_date,'2026-10-20');
  const completed=await rpc('set_crm_work_item_status',[original.id,'completed']);
  assert.ok(completed.completed_at);
  await rejectsInSavepoint(()=>save({id:original.id,title:'Mở lại',startDate:'2026-10-10',dueDate:'2026-10-20',status:'pending'}),/không thể mở lại/);
});

test('complete and cancel keep historical rows queryable with correct completion time',async()=>{
  const completed=await save({title:'Hoàn tất'});const cancelled=await save({title:'Không làm nữa'});
  const completedResult=await rpc('set_crm_work_item_status',[completed.id,'completed']);
  const cancelledResult=await rpc('set_crm_work_item_status',[cancelled.id,'cancelled']);
  assert.equal(completedResult.status,'completed');assert.ok(completedResult.completed_at);
  assert.equal(cancelledResult.status,'cancelled');assert.equal(cancelledResult.completed_at,null);
  assert.equal((await list()).rows.length,0,'default view prioritizes open work');
  assert.equal((await list({status:'completed'})).rows.length,1);
  assert.equal((await list({status:'cancelled'})).rows.length,1);
  assert.equal((await list({includeClosed:true})).rows.length,2);
});

test('search, work type, status, assignee and date filters are applied',async()=>{
  await save({title:'Treo banner mùa hè',type:'banner',customerId:1,assigneeId:assignee,dueDate:'2026-10-20',status:'in_progress'});
  await save({title:'Gọi xác nhận nội dung',type:'customer_followup',customerId:2,dueDate:'2026-11-01'});
  assert.equal((await list({search:'mùa hè'})).rows.length,1);
  assert.equal((await list({type:'banner'})).rows.length,1);
  assert.equal((await list({status:'in_progress'})).rows.length,1);
  assert.equal((await list({assigneeId:assignee})).rows.length,1);
  assert.equal((await list({fromDate:'2026-10-01',toDate:'2026-10-31'})).rows.length,1);
});

test('create, edit, complete and cancel write audit history without using audit_logs as storage',async()=>{
  const first=await save({title:'Audit task'});
  await save({id:first.id,title:'Audit task updated'});
  await rpc('set_crm_work_item_status',[first.id,'completed']);
  const second=await save({title:'Cancel audit'});
  await rpc('set_crm_work_item_status',[second.id,'cancelled']);
  await db.exec('reset role');
  const actions=(await db.query("select action from public.audit_logs where module='WorkItems' order by id")).rows.map(row=>row.action);
  assert.deepEqual(actions,['create_work_item','update_work_item','complete_work_item','create_work_item','cancel_work_item']);
  assert.equal(Number(await scalar('select count(*) from public.crm_work_items')),2);
});
