import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { NAV_SECTIONS } from '../src/constants/navigation.js';
import { canAccessRoute } from '../src/constants/permissions.js';
import { AppLayout } from '../src/layouts/AppLayout.js';

const migrationUrl = new URL('../supabase/migrations/20261010222058_employee_website_user_link.sql', import.meta.url);

test('Employee correction seeds and enforces the dedicated employees permission', async () => {
  const migration = await readFile(migrationUrl, 'utf8');
  assert.match(migration, /values\('employees','Nhân viên',135,true\)/);
  assert.match(migration, /create policy employees_permission_read[^]*has_user_permission\('employees'\)/);
  for (const functionName of ['get_employees_data', 'save_employee', 'set_employee_lifecycle']) {
    const start = migration.indexOf(`function public.${functionName}`);
    assert.ok(start >= 0, functionName);
    const body = migration.slice(start, migration.indexOf('end $$;', start) + 7);
    assert.match(body, /has_user_permission\('employees'\)/, functionName);
    assert.doesNotMatch(body, /has_user_permission\('expenses'\)/, functionName);
  }
});

test('internal sidebar removes personal portal links while public anonymous routes remain registered', async () => {
  const routes = NAV_SECTIONS.flatMap(section => section.items.map(item => item.route));
  const obsolete = ['user', 'user-profile', 'user-kiosks', 'user-register-kiosk', 'payments-mine', 'user-announcements', 'user-support', 'register'];
  for (const route of obsolete) assert.equal(routes.includes(route), false, route);
  assert.deepEqual(NAV_SECTIONS.map(section => section.label), ['TỔNG QUAN', 'QUẢN LÝ CRM', 'NHÂN SỰ', 'HỆ THỐNG']);
  assert.ok(routes.includes('employees'));
  assert.ok(routes.includes('homepage-content'));

  const markup = AppLayout({ navSections: NAV_SECTIONS, user: { username: 'staff', web_access_enabled: true } });
  assert.doesNotMatch(markup, /href="#\/(?:user|user-profile|user-kiosks|user-register-kiosk|payments-mine|user-announcements|user-support|register)"/);
  assert.match(markup, /Nhân sự CRM/);

  const app = await readFile(new URL('../src/app.js', import.meta.url), 'utf8');
  assert.match(app, /const PUBLIC_ROUTES = new Set\(\['home', 'register', 'legacy-registration', 'lookup', 'login', 'signup'\]\)/);
  assert.match(app, /const pages = \{ home: HomePage, register: RegisterPage, 'legacy-registration': LegacyRegistrationPage, lookup: LookupPage/);
});

test('Admin and Staff share navigation definitions while module visibility still follows permissions', () => {
  const staff = { status: 'active', web_access_enabled: true, is_system_admin: false, permissions: ['customers', 'employees'] };
  const expensesOnly = { ...staff, permissions: ['expenses'] };
  const admin = { ...staff, is_system_admin: true, permissions: [] };
  assert.equal(canAccessRoute(staff, 'customers'), true);
  assert.equal(canAccessRoute(staff, 'employees'), true);
  assert.equal(canAccessRoute(staff, 'expenses'), false);
  assert.equal(canAccessRoute(expensesOnly, 'employees'), false);
  assert.equal(canAccessRoute(expensesOnly, 'expenses'), true);
  assert.equal(canAccessRoute(staff, 'kiosks'), false);
  assert.equal(canAccessRoute(admin, 'kiosks'), true);
  assert.equal(canAccessRoute(admin, 'employees'), true);
  assert.equal(NAV_SECTIONS.some(section => /staff/i.test(section.label)), false);
});

test('nullable one-to-one Employee link preserves independent Employee and Website User lifecycles', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create schema auth;
      create table public.app_permissions(permission text primary key,display_name text not null,sort_order integer not null default 0,is_active boolean not null default true);
      create table public.user_profiles (
        user_id uuid primary key,
        username text,
        display_name text,
        status text not null default 'active',
        web_access_enabled boolean not null default false,
        is_system_admin boolean not null default false
      );
      create table public.employees (
        id bigint generated by default as identity primary key,
        full_name text not null,
        phone text,
        job_title text,
        start_date date,
        employment_status text not null default 'active',
        notes text,
        archived_at timestamptz,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now()
      );
      create schema private;
      create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
      create function public.has_user_permission(text) returns boolean language sql stable as $$ select true $$;
      create function private.log_employee_change(public.employees,public.employees,text) returns void language plpgsql as $$ begin return; end $$;
    `);
    await db.exec(await readFile(migrationUrl, 'utf8'));

    const employeeId = (await db.query("insert into public.employees(full_name) values('Nhân viên không login') returning id")).rows[0].id;
    assert.equal((await db.query('select user_id from public.employees where id=$1', [employeeId])).rows[0].user_id, null);

    const userId = '22222222-2222-4222-8222-222222222222';
    await db.query("insert into public.user_profiles(user_id,username,display_name) values($1,'staff','Nhân viên CRM')", [userId]);
    assert.equal((await db.query('select count(*)::int count from public.employees')).rows[0].count, 1, 'Website User may exist without creating Employee');

    await db.query('update public.employees set user_id=$1 where id=$2', [userId, employeeId]);
    await assert.rejects(
      db.query("insert into public.employees(full_name,user_id) values('Trùng link',$1)", [userId]),
      /unique|duplicate/i,
    );
    await db.query('delete from public.user_profiles where user_id=$1', [userId]);
    const retained = (await db.query('select full_name,user_id from public.employees where id=$1', [employeeId])).rows[0];
    assert.equal(retained.full_name, 'Nhân viên không login');
    assert.equal(retained.user_id, null);
  } finally {
    await db.close();
  }
});
